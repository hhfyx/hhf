def set_para_text(p, text):
    if p.runs:
        p.runs[0].text = text
        for r in p.runs[1:]:
            r.text = ""
    else:
        p.add_run(text)


def set_cell_text(cell, text):
    # 保留首段格式，清掉多余段落
    p = cell.paragraphs[0]
    set_para_text(p, text)
    for extra in cell.paragraphs[1:]:
        extra._element.getparent().remove(extra._element)


def png_size(path):
    with open(path, "rb") as f:
        head = f.read(24)
    w = int.from_bytes(head[16:20], "big")
    h = int.from_bytes(head[20:24], "big")
    return w, h


def main():
    shutil.copyfile(SRC, OUT)
    doc = Document(OUT)

    hits = set()
    for p in doc.paragraphs:
        t = p.text
        for key, new in REPL.items():
            if t.startswith(key):
                set_para_text(p, new)
                hits.add(key)
                break

    for ti, cells in TABLES.items():
        tb = doc.tables[ti]
        for (r, c), v in cells.items():
            set_cell_text(tb.cell(r, c), v)

    # 重设图片尺寸（按各自宽高比，宽 6.2 英寸）
    for sh in doc.inline_shapes:
        blip = sh._inline.xpath(".//a:blip")[0]
        rid = blip.get(qn("r:embed"))
        fname = IMG[rid]
        w, h = png_size(HERE / fname)
        sh.width = Inches(6.2)
        sh.height = Inches(6.2 * h / w)
        # 替换图片本体
        doc.part.related_parts[rid]._blob = (HERE / fname).read_bytes()
        print(f"图 {rid} -> {fname}  {w}x{h} -> 6.20 x {6.2*h/w:.2f} in")

    doc.save(OUT)
    miss = set(REPL) - hits
    print("已生成:", OUT)
    print("未匹配到的替换键（应为空）:", miss if miss else "无")


if __name__ == "__main__":
    main()